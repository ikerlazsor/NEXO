"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../..");
const sources = [
  "lib/externalEventClassification.cjs",
  "lib/externalEventPolicy.cjs",
  "scripts/events/social-snapshot.cjs",
  "scripts/events/providers.cjs",
  "scripts/events/geocode.cjs",
  "scripts/madrid-events-preview.cjs",
  "scripts/madrid-events-fetch.cjs",
  "scripts/madrid-events-sync.cjs",
  "scripts/events/madrid-sync-handler.cjs",
];

/** Bundle only the reviewed local modules; no npm/CDN downloads on Edge startup. */
function buildSyncFunction() {
  let output = `// Generated by scripts/events/build-sync-function.cjs. Do not edit.\n`;
  output += `import * as nodeCrypto from "node:crypto";\nimport { Buffer } from "node:buffer";\n`;
  output += `const factories = {};\nconst cache = {};\n`;
  for (const source of sources) {
    const body = fs
      .readFileSync(path.join(root, source), "utf8")
      .replace(/^#![^\n]*\n/, "");
    const dependencies = {};
    for (const match of body.matchAll(/require\("([^"]+)"\)/g)) {
      if (!match[1].startsWith(".")) continue;
      const resolved = path.posix.normalize(
        path.posix.join(path.posix.dirname(source), match[1]),
      );
      if (!sources.includes(resolved))
        throw new Error(`Unreviewed Edge dependency: ${resolved}`);
      dependencies[match[1]] = resolved;
    }
    output += `factories[${JSON.stringify(source)}] = function(module) {\n`;
    output += `const require = (id) => id === "node:crypto" ? nodeCrypto : load(${JSON.stringify(dependencies)}[id]);\n`;
    output += body + "\n};\n";
  }
  output += `function load(id) {\nif (cache[id]) return cache[id].exports;\nif (!factories[id]) throw new Error("Unsupported Edge module");\nconst module = { exports: {} };\ncache[id] = module;\nfactories[id](module);\nreturn module.exports;\n}\n`;
  output += `const { createMadridSyncHandler } = load("scripts/events/madrid-sync-handler.cjs");\n`;
  output += `export { createMadridSyncHandler };\n`;
  output += `if (typeof Deno !== "undefined") Deno.serve(createMadridSyncHandler({ env: Deno.env.toObject() }));\n`;
  return output;
}
if (require.main === module) {
  const target = path.join(
    root,
    "supabase/functions/sync-madrid-events/index.ts",
  );
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, buildSyncFunction());
  console.log("Built sync-madrid-events from the shared, tested importer");
}
module.exports = { buildSyncFunction };
